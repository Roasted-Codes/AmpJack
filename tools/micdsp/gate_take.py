"""A mic test recording -> tests/gate_take.h: its 20 ms windows as mean squares, nothing else.

    python3 tools/micdsp/gate_take.py TAKE.wav [OUT.h]    # default tests/gate_take.h

The recording is a mic test clip saved with `voice.py mictest save` (24 kHz mono, after the
DC removal, at MIC VOLUME 5 = 100 %, so before any gain) made with the gate OFF. Only the
window levels go into the header (one integer per 20 ms: no audio, nothing that could be
played back or identify the speaker); the recording itself is never committed (*.wav is
ignored). tests/test_micdsp360.c rebuilds a signal with exactly these window levels and runs
the plugin's gate on it.
"""
import array
import os
import sys
import wave

RATE, WIN = 24000, 480


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "..", "tests", "gate_take.h")
    with wave.open(src, "rb") as w:
        if w.getnchannels() != 1 or w.getsampwidth() != 2 or w.getframerate() != RATE:
            raise SystemExit(f"{src}: want 24 kHz mono s16 (a voice.py mictest save)")
        x = array.array("h", w.readframes(w.getnframes()))
    if sys.byteorder == "big":
        x.byteswap()
    ms = [sum(v * v for v in x[i:i + WIN]) // WIN for i in range(0, len(x) - WIN + 1, WIN)]
    lines = [
        "/* Generated by tools/micdsp/gate_take.py: do not edit. */",
        "/* The owner reading two sentences twice, gate OFF, MIC VOLUME 5, 30 s of a mic test",
        " * clip: each 20 ms window's mean square (sum x^2 / 480, full scale 2^30). Room floor",
        " * about -74 dBFS, speech -60 .. -30. tests/test_micdsp360.c --gate runs the gate on it. */",
        f"#define GT_WINDOWS {len(ms)}",
        "static const u32 gt_ms[GT_WINDOWS] = {",
    ]
    for i in range(0, len(ms), 10):
        lines.append("\t" + ", ".join(str(v) for v in ms[i:i + 10]) + ",")
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{out}: {len(ms)} windows")


if __name__ == "__main__":
    main()
