"""Exports the test vectors for tests/test_micdsp.c from the integer model (micdsp.py).

    python3 tools/micdsp/vectors.py      # writes tools/micdsp/vectors.h (generated: do not edit)

No numpy needed. The input is an integer generator both sides implement (an LCG noise times a
piecewise-linear envelope, a 150 Hz sawtooth "voice", a +60 DC offset like the real mic), so
only the expected results are stored: the per-window trace of the first scenario in full, and
for every scenario a hash of the trace and of the 8 kHz output.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import micdsp as M  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.h")

# (ms, envelope at the start, at the end): quiet floor, words with soft and hard starts,
# pauses, a shout into the limiter, a floor step up and back down
SEGS = [
    (1200, 8, 8), (40, 8, 2500), (260, 2500, 1800), (80, 1800, 300), (120, 300, 300),
    (60, 300, 3000), (300, 3000, 1500), (90, 1500, 8), (900, 8, 8), (100, 8, 600),
    (200, 600, 2600), (250, 2600, 2000), (100, 2000, 8), (500, 8, 8), (30, 8, 40000),
    (250, 40000, 30000), (60, 30000, 8), (700, 8, 8), (20, 8, 3500), (400, 3500, 3000),
    (60, 3000, 500), (40, 500, 2800), (500, 2800, 2200), (80, 2200, 8), (1000, 8, 8),
    (3500, 160, 160), (60, 160, 4000), (300, 4000, 3500), (60, 3500, 160), (600, 160, 160),
    (3000, 8, 8), (40, 8, 1200), (600, 1200, 900), (80, 900, 8), (1500, 8, 8),
]
SEED = 12345
MUTE = (11000, 12000)      # ms: muted (the mute sends silence; the trackers keep listening)
AUTO_AT = 1000             # ms: MIC VOLUME switched from the scenario's manual level to AUTO

# name, gate, level (0 = AUTO from AUTO_AT on), manual level before, fir, comb, mute
SCEN = [
    ("auto_all", M.GATE_AUTO, 0, 7, True, False, True),
    ("auto_comb", M.GATE_AUTO, 0, 5, True, True, False),
    ("gate_off_agc", M.GATE_OFF, 0, 3, True, False, False),
    ("step2_5", M.GATE_2, 5, 5, False, False, True),
    ("step4_8", M.GATE_4, 8, 8, False, False, False),
    ("step1_10_fir", M.GATE_1, 10, 10, True, False, False),
]


def gen():
    s = SEED
    x = []
    i = 0
    for ms, a0, a1 in SEGS:
        n = ms * 24
        for j in range(n):
            s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
            r = (s >> 16) - 32768
            amp = (a0 * (n - j) + a1 * j) // n
            saw = (i % 160) * 409 - 32720
            v = ((r * amp) >> 16) + ((saw * amp) >> 16) + 60
            x.append(M.clamp16(v))
            i += 1
    return x


def fnv(vals, h=0x811C9DC5):
    for v in vals:
        v &= 0xFFFFFFFF
        for k in range(4):
            h ^= (v >> (8 * k)) & 0xFF
            h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def run(x, gate, level, manual, fir, comb, mute):
    p = M.Pad(gate=gate, level=manual, fir=fir, comb=comb)
    out = []
    for c in range(0, len(x), 24):
        ms = c // 24
        if level == 0 and ms == AUTO_AT:
            p.set_level(0)
        p.muted = mute and MUTE[0] <= ms < MUTE[1]
        out.extend(p.chunk(x[c:c + 24]))
    return p, out


def main():
    x = gen()
    lines = ["/* generated by tools/micdsp/vectors.py from the integer model: do not edit */",
             f"#define MV_SEED {SEED}u", f"#define MV_MUTE_FROM {MUTE[0]}",
             f"#define MV_MUTE_TO {MUTE[1]}", f"#define MV_AUTO_AT {AUTO_AT}",
             f"#define MV_SAMPLES {len(x)}",
             "static const u32 mv_segs[][3] = {"]
    lines += [f"\t{{ {a}, {b}, {c} }}," for a, b, c in SEGS]
    lines += ["};", "struct mv_scen { const char *name; u32 gate, level, manual, fir, comb, mute;"
              " u32 windows, trace_hash, out_n, out_hash; };", "static const struct mv_scen mv_scen[] = {"]
    first = None
    for name, gate, level, manual, fir, comb, mute in SCEN:
        p, out = run(x, gate, level, manual, fir, comb, mute)
        flat = [v for row in p.trace for v in row]
        lines.append(f'\t{{ "{name}", {gate}, {level}, {manual}, {int(fir)}, {int(comb)}, {int(mute)},'
                     f" {len(p.trace)}, 0x{fnv(flat):08x}u, {len(out)}, 0x{fnv(out):08x}u }},")
        first = first or p.trace
        print(f"{name}: {len(p.trace)} windows, {len(out)} out, last gain q12 {p.agc.q12},"
              f" floor {p.floor.floor_db / 256:.1f} dBFS")
    lines.append("};")
    lines.append("/* scenario 0, every window: rms, thr, open, floor_db, thr_db, q12, speech_db */")
    lines.append(f"static const s32 mv_trace0[{len(first)}][7] = {{")
    lines += ["\t{ " + ", ".join(str(v) for v in row) + " }," for row in first]
    lines.append("};")
    # unit vectors: the log / exp helpers and the decimator's impulse response
    ms_vals = [1, 2, 3, 5, 7, 100, 1000, 4095, 4096, 12345, 1 << 20, 99999999, 1 << 30]
    lines.append("static const u32 mv_ms[] = { " + ", ".join(str(v) for v in ms_vals) + " };")
    lines.append("static const s32 mv_db_ms[] = { " + ", ".join(str(M.db_ms(v)) for v in ms_vals) + " };")
    dbs = [-25600, -15360, -11520, -8960, -7680, -3082, -1, 0, 1, 2560, 3830]
    lines.append("static const s32 mv_db[] = { " + ", ".join(str(v) for v in dbs) + " };")
    lines.append("static const u32 mv_lin15[] = { " + ", ".join(str(M.lin(v, 15)) for v in dbs) + " };")
    lines.append("static const u32 mv_lin12[] = { " + ", ".join(str(M.lin(v, 12)) for v in dbs) + " };")
    q = [1024, 1433, 2048, 2867, 4096, 5734, 8192, 11468, 16384, 22937]
    lines.append("static const s32 mv_db_q12[] = { " + ", ".join(str(M.db_q12(v)) for v in q) + " };")
    f = M.Fir()
    imp = [v for v in (f.push(32767 if i == 0 else 0) for i in range(3 * 20)) if v is not None]
    lines.append("static const s16 mv_fir_imp[] = { " + ", ".join(str(v) for v in imp) + " };")
    c = M.Comb()
    comb = [c.push(v) for v in x[:4000]]
    lines.append(f"#define MV_COMB_HASH 0x{fnv(comb):08x}u /* the first 4000 inputs */")
    # the mic test's playback (micdsp.playback) at step 2 and MIC VOLUME 7, the first 3 s
    play = M.playback(x[:72000], 58, 8192)
    lines.append(f"#define MV_PLAY_HASH 0x{fnv(play):08x}u /* playback(x[:72000], 58, 8192) */")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
